export type MessageKey = keyof (typeof messages)['en'];

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly language = signal<GlacierLanguage>(this.browserLanguage());

  constructor() {
    document.documentElement.lang = this.language();
  }

  set(language: GlacierLanguage): void {
    this.language.set(language);
    document.documentElement.lang = language;
  }

  t(key: MessageKey, placeholders?: MessagePlaceholders): string {
    const template: string = messages[this.language()][key];
    if (!placeholders) return template;
    return Object.entries(placeholders).reduce<string>(
      (text, [name, value]) => text.replace(`{${name}}`, String(value)),
      template,
    );
  }

  formatDate(value: string | Date): string {
    return new Intl.DateTimeFormat(this.language() === 'de' ? 'de-AT' : 'en', {
      dateStyle: 'medium',
      timeStyle: 'short',
    }).format(new Date(value));
  }

  private browserLanguage(): GlacierLanguage {
    return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
  }
}

